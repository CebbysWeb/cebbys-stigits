/** Russian plural form: 1 карта, 2 карты, 5 карт. */
const ruPlural = (n: number, one: string, few: string, many: string): string => {
  const a = Math.abs(n) % 100
  const b = a % 10
  return a > 10 && a < 20 ? many : b === 1 ? one : b >= 2 && b <= 4 ? few : many
}

