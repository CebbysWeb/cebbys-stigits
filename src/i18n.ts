let current: Lang = 'en'

export function setLang(lang: Lang): void {
  current = lang
  document.documentElement.lang = lang
}

export const getLang = (): Lang => current

/** The text for `key` in the current language. */
export const t: Dict = new Proxy(en, { get: (_, key: keyof Dict) => DICTS[current][key] }) as Dict

export const translateError = (message: string): string => ERRORS[message]?.[current] ?? message

/** The browser's language if the game speaks it, otherwise English. */
export function guessLang(): Lang {
  const code = (navigator.language || 'en').slice(0, 2).toLowerCase()
  return (LANGS as string[]).includes(code) ? (code as Lang) : 'en'
}

